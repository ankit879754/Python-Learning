# String Indexing
# Positive indexing :-
# R o h a n
# 0 1 2 3 4
# Example
my_name = "Rohan"
print(my_name)
print(my_name[1]) #o
print(my_name[2]) #h
print(my_name[4]) #n
_______________________________________
# Negative Indexing
# R o h a n
# -5 -4 -3 -2 -1
# Examples
my_name = "Rohan"
print(my_name)
print(my_name[-1]) #n
print(my_name[-3]) #h
_____________________________________